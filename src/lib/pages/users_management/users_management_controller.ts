export interface UpdateUserInput {
  full_name: string;
  phone_number: string;
  address: string;
  username: string;
  email: string;
  status: string;
  password?: string; // optional: blank = keep current
}

export interface ScopeInput {
  scope_level: number; // 1 = all, 2 = region, 3 = province, 4 = municipality
  reg_code: string | null;
  pro_code: string | null;
  mun_code: string | null;
  poi: boolean;
  smv: boolean;
  psa: boolean;
}

/* turns a Postgres unique-violation into { error, field } (or null if it's something else) */
export function parseUniqueViolation(err: any): { error: string; field?: string } | null {
  if (err?.code !== "23505") return null;
  const field = /\((\w+)\)=/.exec(err.detail ?? "")?.[1];
  const labels: Record<string, string> = { username: "Username", email: "Email" };
  return {
    error: field && labels[field] ? `${labels[field]} already exists` : `Duplicate value${field ? ` for ${field}` : ""}`,
    field,
  };
}

export async function updateUser(id: number, u: UpdateUserInput) {
  const params: any[] = [
    u.full_name.trim(), u.phone_number.trim(), u.address.trim(),
    u.username.trim(), u.email.trim(), u.status, id,
  ];
  let passwordSql = "";
  if (u.password) {
    params.push(await bcrypt.hash(u.password, 10));
    passwordSql = ", password_hash = $8";
  }
  const res = await conn.query(
    `UPDATE data.users
        SET full_name = $1, phone_number = $2, address = $3,
            username = $4, email = $5, status = $6, updated_at = now()
            ${passwordSql}
      WHERE id = $7`,
    params
  );
  return (res.rowCount ?? 0) > 0;
}

export async function deleteUser(id: number) {
  const client = await conn.connect();
  try {
    await client.query("BEGIN");
    await client.query(
      `DELETE FROM data.scope
        WHERE user_id = (SELECT user_id FROM data.users WHERE id = $1)`,
      [id]
    );
    const res = await client.query(`DELETE FROM data.users WHERE id = $1`, [id]);
    await client.query("COMMIT");
    return (res.rowCount ?? 0) > 0;
  } catch (err) {
    await client.query("ROLLBACK");
    throw err;
  } finally {
    client.release();
  }
}

/* current scopes of a user, with names from core.muni_bndry (levels 1-4 only) */
export async function loadUserScopes(id: number) {
  const { rows } = await conn.query(
    `SELECT s.scope_id, s.scope_level,
            CASE WHEN s.scope_level >= 2 THEN COALESCE(s.reg_code, n.reg_code) END AS reg_code,
            CASE WHEN s.scope_level >= 3 THEN COALESCE(s.pro_code, n.pro_code) END AS pro_code,
            CASE WHEN s.scope_level >= 4 THEN COALESCE(s.mun_code, n.mun_code) END AS mun_code,
            s.poi, s.smv, s.psa,
            n.reg_name, n.pro_name, n.mun_name
       FROM data.scope s
       LEFT JOIN LATERAL (
         SELECT m.reg_code, m.reg_name, m.pro_code, m.pro_name, m.mun_code, m.mun_name
           FROM core.muni_bndry m
          WHERE (s.scope_level = 2 AND m.reg_code = s.reg_code)
             OR (s.scope_level = 3 AND m.pro_code = s.pro_code)
             OR (s.scope_level = 4 AND m.mun_code = s.mun_code)
          LIMIT 1
       ) n ON true
      WHERE s.user_id = (SELECT user_id FROM data.users WHERE id = $1)
        AND s.scope_level BETWEEN 1 AND 4
      ORDER BY s.scope_level, s.scope_id`,
    [id]
  );
  return rows;
}

/* replaces the user's scope rows (levels 1-4) in one transaction */
export async function replaceUserScopes(id: number, scopes: ScopeInput[]) {
  const client = await conn.connect();
  try {
    await client.query("BEGIN");

    const u = await client.query(`SELECT user_id FROM data.users WHERE id = $1`, [id]);
    if (!u.rowCount) {
      await client.query("ROLLBACK");
      return false;
    }
    const userId = u.rows[0].user_id;

    await client.query(
      `DELETE FROM data.scope WHERE user_id = $1 AND scope_level BETWEEN 1 AND 4`,
      [userId]
    );

    for (const s of scopes) {
      await client.query(
        `INSERT INTO data.scope
           (user_id, scope_level, reg_code, pro_code, mun_code, poi, smv, psa)
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8)`,
        [userId, s.scope_level, s.reg_code, s.pro_code, s.mun_code, s.poi, s.smv, s.psa]
      );
    }

    await client.query("COMMIT");
    return true;
  } catch (err) {
    await client.query("ROLLBACK");
    throw err;
  } finally {
    client.release();
  }
}
