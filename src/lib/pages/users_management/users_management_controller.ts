import bcrypt from "bcryptjs";
import { conn } from "@/lib/db";


const SCOPE_LEVEL: Record<string, number> = {
  region: 2,
  province: 3,
  municipality: 4,
};

export interface LocationRow {
  reg_code: string;
  reg_name: string;
  pro_code: string;
  pro_name: string;
  mun_code: string;
  mun_name: string;
}

export interface NewUserInput {
  full_name: string;
  phone_number: string;
  address: string;
  username: string;
  email: string;
  status: string;
  password: string;
}

export interface NewScopeInput {
  scope_level: "region" | "province" | "municipality";
  reg_code: string | null;
  pro_code: string | null;
  mun_code: string | null;
}

/* Dropdown source. geom is intentionally NOT selected (too heavy for a dropdown). */
export async function loadLocations(): Promise<LocationRow[]> {
  const { rows } = await conn.query<LocationRow>(
    `SELECT DISTINCT reg_code, reg_name, pro_code, pro_name, mun_code, mun_name
       FROM core.muni_bndry
      ORDER BY reg_name, pro_name, mun_name`
  );
  return rows;
}

/* 1 row in data.users + 1..n rows in data.scope, in a single transaction */
/* 1 row in data.users + 1..n rows in data.scope, one transaction */
export async function createUser(
  user: NewUserInput,
  scopes: NewScopeInput[],
  modules: string[]
) {
  const client = await conn.connect();
  try {
    await client.query("BEGIN");

    const passwordHash = await bcrypt.hash(user.password, 10);

    // user_id is generated by the column default (data.generate_user_id())
    const userRes = await client.query(
      `INSERT INTO data.users
         (username, email, password_hash, full_name, phone_number, address, status)
       VALUES ($1, $2, $3, $4, $5, $6, $7)
       RETURNING user_id`,
      [
        user.username.trim(),
        user.email.trim(),
        passwordHash,
        user.full_name.trim(),
        user.phone_number.trim(),
        user.address.trim(),
        user.status,
      ]
    );
    const userId = userRes.rows[0].user_id;

    const poi = modules.includes("POI");
    const smv = modules.includes("SMV");
    const psa = modules.includes("PSA");

    for (const s of scopes) {
      await client.query(
        `INSERT INTO data.scope
           (user_id, scope_level, reg_code, pro_code, mun_code, poi, smv, psa)
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8)`,
        [userId, SCOPE_LEVEL[s.scope_level], s.reg_code, s.pro_code, s.mun_code, poi, smv, psa]
      );
    }

    await client.query("COMMIT");
    return { user_id: userId };
  } catch (err) {
    await client.query("ROLLBACK");
    throw err;
  } finally {
    client.release();
  }
}

